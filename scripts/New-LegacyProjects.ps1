# Writes src/legacy/<V>/MacroHid.Legacy.<V>.csproj for every snapshot in Legacy-Versions.ps1.
# The project compiles the release's Core and Runtime sources unchanged plus src/legacy/Bridge/LegacyBridge.cs.
$ErrorActionPreference = "Stop"
$repoRoot = Resolve-Path (Join-Path $PSScriptRoot "..")
. (Join-Path $PSScriptRoot "Legacy-Versions.ps1")

function Get-Features([string]$tag) {
    $v = [version]$tag.TrimStart('v')
    $features = @()
    if ($v -ge [version]"1.6.0") { $features += "LEGACY_BACKGROUND_OPTIONS", "LEGACY_LAST_ERROR" }
    if ($v -ge [version]"1.4.1") { $features += "LEGACY_MASK_WARMUP" }
    if ($v -eq [version]"1.6.0") { $features += "LEGACY_MASK_CLEAR_SHUTDOWN" }
    if ($v -ge [version]"2.0.1") { $features += "LEGACY_PATH_WARMUP" }
    if ($v -le [version]"1.6.0") { $features += "LEGACY_EXTERNAL_HOOK" }
    $features
}

foreach ($version in $LegacyVersions) {
    $folder = Join-Path $repoRoot (Join-Path "src\legacy" $version.Folder)
    $parser = Get-Content (Join-Path $folder "Core\McrxParser.cs") -Raw -Encoding UTF8
    $start = $parser.IndexOf("MacroStep ParseStep(")
    if ($start -lt 0) { throw "ParseStep not found in $($version.Folder)" }
    $end = $parser.IndexOf("_ => throw", $start)
    $types = [regex]::Matches($parser.Substring($start, $end - $start), '"([a-z0-9.\-]+)"\s*=>') | ForEach-Object { $_.Groups[1].Value } | Sort-Object -Unique
    $runtimeProject = Get-Content (Join-Path $folder "Runtime\MacroHid.Runtime.csproj.original") -Raw
    $weakNet = $runtimeProject -match "WinDivert"
    $netLimiter = [regex]::Match($runtimeProject, 'PackageReference Include="NetLimiter" Version="([^"]+)"')
    $unsafe = $runtimeProject -match "AllowUnsafeBlocks"
    $features = (Get-Features $version.Tag) -join ";"
    $plainVersion = $version.Tag.TrimStart('v')
    $resources = if ($weakNet) { @"

  <ItemGroup>
    <EmbeddedResource Include="Runtime\WeakNet\Native\WinDivert.dll" LogicalName="WinDivert.dll" />
    <EmbeddedResource Include="Runtime\WeakNet\Native\WinDivert64.sys" LogicalName="WinDivert64.sys" />
  </ItemGroup>
"@ } else { "" }
    $package = if ($netLimiter.Success) { @"

  <ItemGroup>
    <PackageReference Include="NetLimiter" Version="$($netLimiter.Groups[1].Value)" />
  </ItemGroup>
"@ } else { "" }
    $project = @"
<Project Sdk="Microsoft.NET.Sdk">
  <!-- Generated by scripts/New-LegacyProjects.ps1. MacroHID $plainVersion playback code ($($version.Tag)), unchanged except the
       files in patched-files.txt, compiled as one assembly so it can run next to the current runtime. -->
  <PropertyGroup>
    <TargetFramework>net8.0</TargetFramework>
    <ImplicitUsings>enable</ImplicitUsings>
    <Nullable>enable</Nullable>
    <AllowUnsafeBlocks>$($unsafe.ToString().ToLowerInvariant())</AllowUnsafeBlocks>
    <AssemblyName>MacroHid.Legacy.$($version.Folder)</AssemblyName>
    <RootNamespace>MacroHid.Legacy.$($version.Folder)</RootNamespace>
    <DefineConstants>`$(DefineConstants);$features</DefineConstants>
    <!-- The release's code as it was: its warnings are not ours to fix. -->
    <NoWarn>`$(NoWarn);CS0168;CS0219;CS0414;CS0649;CS0169;CS1998;CS8600;CS8601;CS8602;CS8603;CS8604;CS8618;CS8619;CS8620;CS8625;CS8629;CS8765;CS8767;CA1416;CA2022;NU1701</NoWarn>
    <TreatWarningsAsErrors>false</TreatWarningsAsErrors>
    <GenerateDocumentationFile>false</GenerateDocumentationFile>
  </PropertyGroup>

  <ItemGroup>
    <Compile Remove="Native\**" />
    <None Remove="Native\**" />
    <Compile Include="..\Bridge\LegacyBridge.cs" Link="LegacyBridge.cs" />
$(if ((Get-Features $version.Tag) -contains "LEGACY_EXTERNAL_HOOK") { '    <Compile Include="..\Bridge\LegacyExternalStep.cs" Link="LegacyExternalStep.cs" />' })
    <AssemblyMetadata Include="LegacyVersion" Value="$plainVersion" />
    <AssemblyMetadata Include="LegacySuffix" Value="$($version.Suffix)" />
    <AssemblyMetadata Include="LegacyStepTypes" Value="$($types -join ';')" />
  </ItemGroup>

  <ItemGroup>
    <ProjectReference Include="..\MacroHid.LegacyContract\MacroHid.LegacyContract.csproj" />
  </ItemGroup>
$resources$package
  <ItemGroup>
    <!-- Built by scripts/Build-LegacyNative.ps1 from Native\ (the release's own native source). -->
    <None Include="Native\x64\Release\MacroHid.NativePlayback.$($version.Suffix).dll" Condition="Exists('Native\x64\Release\MacroHid.NativePlayback.$($version.Suffix).dll')"
          Link="MacroHid.NativePlayback.$($version.Suffix).dll" CopyToOutputDirectory="PreserveNewest" />
  </ItemGroup>
</Project>
"@
    $path = Join-Path $folder ("MacroHid.Legacy." + $version.Folder + ".csproj")
    [IO.File]::WriteAllText($path, $project, (New-Object Text.UTF8Encoding($false)))
    "$($version.Folder): $($types.Count) step types; features=$features"
}
